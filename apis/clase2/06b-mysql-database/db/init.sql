-- Library database for exercise 06b.
-- Docker runs this file ONLY the first time the container starts with an empty volume.
-- To load it again: docker compose down -v, then docker compose up -d --wait
-- The ISBNs are made up (13 digits with a valid check digit); titles, authors and years are real.

SET NAMES utf8mb4;

CREATE TABLE authors (
  id          INT AUTO_INCREMENT PRIMARY KEY,
  name        VARCHAR(120) NOT NULL UNIQUE,
  country     VARCHAR(60),
  birth_year  SMALLINT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE books (
  id          INT AUTO_INCREMENT PRIMARY KEY,
  title       VARCHAR(200) NOT NULL,
  isbn        CHAR(13) UNIQUE,
  year        SMALLINT,
  author_id   INT NOT NULL,
  created_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  -- RESTRICT: MySQL refuses to delete an author who still has books
  CONSTRAINT fk_books_author FOREIGN KEY (author_id) REFERENCES authors(id) ON DELETE RESTRICT
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

